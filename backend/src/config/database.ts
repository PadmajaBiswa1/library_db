  public logActivity(action: IDailyActivity['action'], title: string, details: string, actor = 'Staff'): void {
    const act: IDailyActivity = {
      id: `act-${Date.now()}`,
      timestamp: new Date().toISOString(),
      action,
      title,
      details,
      actor,
    };
    this.dailyActivities.unshift(act);
    if (this.dailyActivities.length > 50) {
      this.dailyActivities.pop();
    }
  }

  public addNotification(type: INotification['type'], title: string, message: string, recipientId?: string, recipientName?: string): void {
    const notif: INotification = {
      id: `notif-${Date.now()}`,
      type,
      title,
      message,
      recipientId,
      recipientName,
      isRead: false,
      createdAt: new Date().toISOString(),
    };
    this.notifications.unshift(notif);
  }
